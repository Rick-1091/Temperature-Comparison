// Chart renderers sometimes lowercase short labels in tooltips and summaries.
const caseInsensitiveCopy = new Map([...copy].map(([key,value]) => [key.toLowerCase(),value]));
function weatherName(value) { return ({sunny:'晴朗',rainy:'降雨',hot:'炎热',cool:'凉爽',windy:'大风'})[value]; }
function label(value) {
  const labels = {'outdoor café':'户外咖啡店','indoor coworking':'室内共享办公','coworking':'共享办公','indoor leisure':'室内休闲','walking':'步行','cycling':'骑行','park':'公园','museum / indoor leisure':'博物馆 / 室内休闲'};
  return labels[value.toLowerCase()] || copy.get(value) || weatherName(value.toLowerCase()) || value;
}

export function translateChapterThree(source) {
  const direct = copy.get(source) ?? caseInsensitiveCopy.get(source.toLowerCase());
  if (direct != null) return direct;
  if (source.startsWith('On ') && source.includes(', ')) {
    const boundary = source.indexOf(', ');
    return translateChapterThree(source.slice(0, boundary)) + translateChapterThree(source.slice(boundary));
  }
  let result = source;
  for (const [pattern, replacement] of rules) {
    if (pattern.test(result)) { result = result.replace(pattern, replacement); break; }
  }
  if (result === source && source.includes(' · ')) {
    result = source.split(' · ').map(translateChapterThree).join(' · ');
  }
  // English-formatted dates occur in selectors, SVG labels, and fragmented prose.
  const months = {Jan:1,Feb:2,Mar:3,Apr:4,May:5,Jun:6,Jul:7,Aug:8,Sep:9,Oct:10,Nov:11,Dec:12};
  result = result.replace(/\b(January|February|March|April|May|June|July|August|September|October|November|December|Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\s+(\d{1,2})(?:,\s*(2026))?\b/gi,
    (_, month, day, year) => `${year ? year+'年' : ''}${months[month[0].toUpperCase()+month.slice(1,3).toLowerCase()]}月${day}日`);
  result = result.replace(/\b(Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday|Mon|Tue|Wed|Thu|Fri|Sat|Sun)\b/gi,
    (day) => ({mon:'周一',tue:'周二',wed:'周三',thu:'周四',fri:'周五',sat:'周六',sun:'周日'})[day.slice(0,3).toLowerCase()]);
  return result;
}
